def ear(g, side, tip=3, root=7, y0=13, rows=None):
    """尖耳：默认 5 行（y13-17）。rows = [(dy, x0, x1), ...] 可自定义行宽。
    画在头发之上，描边交给 outline()。side=-1 左 / +1 右"""
    if rows is None:
        rows = [(0, root - 1, root), (1, tip, root), (2, tip, root),
                (3, tip + 1, root), (4, root - 1, root)]
    for dy, x0, x1 in rows:
        y = y0 + dy
        xs = list(range(x0, x1 + 1)) if side < 0 else list(range(31 - x1, 31 - x0 + 1))
        for x in xs:
            g[y][x] = 's'
    t = tip + 1 if side < 0 else 31 - tip - 1
    coords(g, [(t, y0 + 2)], 'S')


