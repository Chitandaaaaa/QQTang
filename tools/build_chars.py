def outline_right(g, pts, ch='k'):
    """沿一串点向右补 1px 描边（只画在空处）"""
    for x, y in pts:
        if x + 1 < len(g[0]) and g[y][x + 1] == '.':
            g[y][x + 1] = ch


def plume(g, pts, tip=None):
    """羽毛 / 翎：双像素斜线 + 尖端点色"""
    coords(g, pts, 'n')
    if tip:
        coords(g, tip, 'o')


