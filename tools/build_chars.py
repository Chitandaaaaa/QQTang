def ascii_dump(g, title):
    w = len(g[0])
    print('\n== %s (%dx%d) ==' % (title, w, len(g)))
    print('    ' + ' '.join('01234567' for _ in range((w + 7) // 8)))
    for y, row in enumerate(g):
        line = ''.join(row).replace('.', '·')
        print('%3d %s' % (y, ' '.join(line[i:i + 8] for i in range(0, w, 8))))


def main():
    if len(sys.argv) > 1 and sys.argv[1] == 'ascii':
        for key, fn, label in SPRITES:
            ascii_dump(fn(), label)
        return
    os.makedirs(OUT, exist_ok=True)
    for key, fn, label in SPRITES:
        svg = to_svg(fn(), label, 'QQ糖 · %s · 像素素材（透明底）' % label)
        open(os.path.join(OUT, key + '.svg'), 'w', encoding='utf-8').write(svg)
        print('%-18s %5d bytes' % (key + '.svg', len(svg)))


if __name__ == '__main__':
    main()
