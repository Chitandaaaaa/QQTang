"""
QQ糖 · 夺宝素材库 · 道具（三个 32×32 增益道具）

严格照三张参考图描的 —— 参考图都在 sucai/道具/ 下（真身是 JPEG）：
- 加炮弹威力.png  圆底烧瓶药瓶：软木塞 + 玻璃瓶颈 + 圆肚，药液上粉下青，两侧两颗小星
- 加炮弹数量.png  粉青渐变的「+1」圆珠，四角四颗小星
- 加移动速度.png  粉青渐变球鞋，白色鞋底 + 白鞋带，鞋跟上一片白翅膀，右侧速度线

32px 下只能留「一个大剪影 + 一个特征」，所以三件都按剪影优先重画，共用一套调色板：
深藏青描边 + 粉/青双色渐变 + 白色高光。
"""
import math
from sucai_lib import grid, fill, shape, coords, disc, outline

ITEM = {
    'K': '#2A2440',            # 描边（藏青）
    'w': '#F4F8FF',            # 玻璃 / 鞋底白
    'B': '#CFE3F6',            # 浅蓝（玻璃/鞋面）
    'c': '#9FC6E4',            # 蓝灰阴影
    'p': '#FFA6CE',            # 粉
    'P': '#FFC9DF',            # 浅粉
    'q': '#E4749E',            # 深粉
    'b': '#6FD0F0',            # 青
    'C': '#3FAFDC',            # 深青
    't': '#D08A45',            # 软木
    'T': '#A5672A',            # 软木暗部
    'y': '#F7D77A',            # 星星
    'Y': '#FFF3C4',            # 星星亮芯
    'N': '#FFFFFF',            # 字形白（单独 key，方便自动描边）
}


def _halo(g, ch, out='K'):
    """给指定颜色描一圈外扩边（涂在除自己以外的任何颜色上）。
    用于「画在别的东西内部」的元素 —— 只描 '.' 是不出边的。"""
    h, w = len(g), len(g[0])
    add = []
    for y in range(h):
        for x in range(w):
            if g[y][x] != ch:
                continue
            for nx, ny in ((x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1),
                           (x - 1, y - 1), (x + 1, y - 1), (x - 1, y + 1), (x + 1, y + 1)):
                if 0 <= nx < w and 0 <= ny < h and g[ny][nx] not in (ch, out):
                    add.append((nx, ny))
    for x, y in add:
        g[y][x] = out


def _sparkle(g, cx, cy):
    """四角小星：一横一竖 + 一枚亮芯"""
    coords(g, [(cx, cy - 2), (cx, cy + 2), (cx - 2, cy), (cx + 2, cy)], 'y')
    coords(g, [(cx - 1, cy - 1), (cx + 1, cy - 1), (cx - 1, cy + 1), (cx + 1, cy + 1)], 'Y')
    coords(g, [(cx, cy)], 'Y')


# ------------------------------------------------------------------ 加炮弹威力：药瓶
def prop_power():
    g = grid(32, 32)
    CX, CY, RX, RY = 15.5, 22.0, 9.8, 8.8

    def inside(x, y, rx, ry):
        return ((x - CX) / rx) ** 2 + ((y - CY) / ry) ** 2 <= 1.0

    # 1) 瓶颈 / 瓶口（先画，肚皮盖住接缝）
    shape(g, [(8, 10, 21), (9, 10, 21),
              (10, 12, 19), (11, 12, 19), (12, 12, 19), (13, 12, 19), (14, 11, 20)], 'w')
    # 2) 肚皮（白玻璃）
    for y in range(32):
        for x in range(32):
            if inside(x, y, RX, RY):
                g[y][x] = 'w'
    # 3) 药液：液面第 15 行（平的），往下上粉下青
    for y in range(15, 32):
        for x in range(32):
            if not inside(x, y, RX - 1.5, RY - 1.5):
                continue
            if y >= 28:
                g[y][x] = 'C'
            elif y >= 26:
                g[y][x] = 'b'
            elif x - CX > 4.2:
                g[y][x] = 'b'
            elif y >= 18:
                g[y][x] = 'p'
            else:
                g[y][x] = 'P'
    # 4) 软木塞
    shape(g, [(3, 12, 19), (4, 11, 20), (5, 11, 20), (6, 11, 20), (7, 12, 19)], 't')

    outline(g, 'K')

    # 5) 液面高光（只压一条浅粉，不要白缝）
    for x in range(32):
        if g[15][x] in ('P', 'p'):
            g[15][x] = 'P'
    # 6) 左下高光 + 右下暗部
    coords(g, [(10, 18), (11, 18), (10, 19), (11, 19), (12, 19)], 'w')
    coords(g, [(10, 20), (11, 20)], 'P')
    coords(g, [(20, 22), (20, 23), (21, 23)], 'q')
    # 7) 瓶颈玻璃反光
    for y in range(10, 13):
        coords(g, [(14, y), (17, y)], 'B')
    # 8) 软木塞纹理
    coords(g, [(12, 4), (14, 4), (16, 4), (18, 4),
               (13, 5), (15, 5), (17, 5), (19, 5),
               (12, 6), (15, 6), (17, 6), (19, 6)], 'T')
    # 9) 两侧小星
    _sparkle(g, 4, 13)
    _sparkle(g, 27, 12)
    return g


# ------------------------------------------------------------------ 加炮弹数量：+1 圆珠
def prop_bombs():
    g = grid(32, 32)
    cx, cy = 15.5, 16.0

    disc(g, cx, cy, 11.2, 'p')
    for y in range(32):
        for x in range(32):
            if g[y][x] != 'p':
                continue
            t = (y - 4) / 24.0                       # 纵向渐变：上粉下青
            if t > 0.72:
                g[y][x] = 'b'
            elif t > 0.58:
                g[y][x] = 'B'
            elif t > 0.36:
                g[y][x] = 'P'
    outline(g, 'K')

    # 左上高光
    shape(g, [(9, 9, 12), (10, 8, 13), (11, 8, 12)], 'w')

    # 「+1」字样：白字 + 一圈藏青外扩边（参考图就是描边字）
    shape(g, [(12, 8, 9), (13, 8, 9), (14, 6, 11), (15, 6, 11),
              (16, 6, 11), (17, 8, 9), (18, 8, 9)], 'N')                  # +
    shape(g, [(11, 17, 18), (12, 16, 18), (13, 17, 18), (14, 17, 18),
              (15, 17, 18), (16, 17, 18), (17, 17, 18),
              (18, 16, 21), (19, 16, 21)], 'N')                            # 1
    _halo(g, 'N', 'K')

    # 四角四颗星（在珠子外面）
    _sparkle(g, 3, 5)
    _sparkle(g, 28, 4)
    _sparkle(g, 3, 27)
    _sparkle(g, 28, 28)
    return g


# ------------------------------------------------------------------ 加移动速度：带翅膀的球鞋
def prop_speed():
    g = grid(32, 32)

    # 1) 翅膀（先画，鞋口会盖住根部）：一整片白羽朝右上
    shape(g, [(4, 28, 30), (5, 27, 31), (6, 26, 31), (7, 25, 30),
              (8, 25, 29), (9, 24, 28), (10, 24, 27), (11, 24, 26),
              (12, 24, 25)], 'w')

    # 2) 鞋面：L 形 —— 右边竖起来是鞋口，左边横着的是鞋头
    body = [(11, 20, 24), (12, 19, 25), (13, 19, 25), (14, 19, 25),
            (15, 19, 25),
            (16, 5, 25), (17, 4, 25), (18, 4, 25), (19, 4, 24),
            (20, 4, 24), (21, 5, 23), (22, 6, 22), (23, 8, 21), (24, 10, 20)]
    shape(g, body, 'p')

    # 3) 粉 -> 青 斜向渐变（鞋头粉、鞋跟青）
    for y in range(32):
        for x in range(32):
            if g[y][x] != 'p':
                continue
            t = ((x - 4) / 21.0) * 0.78 + ((y - 16) / 9.0) * 0.22
            if t > 0.86:
                g[y][x] = 'b'
            elif t > 0.68:
                g[y][x] = 'B'
            elif t > 0.48:
                g[y][x] = 'P'

    # 4) 鞋底（白，贴着鞋面下沿，鞋头往前多探 1px）
    shape(g, [(25, 8, 20), (26, 5, 21), (27, 6, 21)], 'w')

    outline(g, 'K')

    # 5) 羽毛暗部（描边之后画，留在里面）
    for (x, y) in [(29, 4), (28, 5), (27, 6), (26, 7),
                   (30, 6), (29, 7), (28, 8), (27, 9), (26, 10),
                   (28, 9), (27, 10), (26, 11)]:
        if g[y][x] == 'w':
            g[y][x] = 'B'
    # 6) 鞋带：三道白杠，压在鞋背上
    for (y, x0, x1) in [(17, 7, 15), (19, 6, 14), (21, 7, 13)]:
        fill(g, y, x0, x1, 'w')
        fill(g, y + 1, x0 + 1, x1, 'N')
    # 7) 鞋口内圈（深一点，让「鞋口」读得出来）
    for x in range(20, 24):
        if g[11][x] == 'p' or g[11][x] == 'P':
            g[11][x] = 'q'
    # 8) 鞋底反光
    for x in range(6, 21):
        if g[26][x] == 'w':
            g[26][x] = 'B'
    # 9) 速度线（鞋跟右侧三道）
    for (y, x0, x1) in [(18, 27, 31), (21, 28, 31), (24, 26, 30)]:
        fill(g, y, x0, x1, 'B')
    return g


